const W = 64;
const H = 24;
const WATERLINE = H - 7;

function mulberry(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function runs(px) {
  // px: Set of "x,y" -> merge horizontal runs into one path.
  const rows = new Map();
  for (const key of px) {
    const [x, y] = key.split(',').map(Number);
    if (!rows.has(y)) rows.set(y, []);
    rows.get(y).push(x);
  }
  let d = '';
  for (const [y, xs] of rows) {
    xs.sort((a, b) => a - b);
    let start = xs[0];
    let prev = xs[0];
    for (let i = 1; i <= xs.length; i++) {
      if (i < xs.length && xs[i] === prev + 1) { prev = xs[i]; continue; }
      d += `M${start} ${y}h${prev - start + 1}v1h${-(prev - start + 1)}z`;
      if (i < xs.length) { start = prev = xs[i]; }
    }
  }
  return d;
}

export function shipArt(category, seed = 1) {
  const art = ART[category] || ART.other;
  const rnd = mulberry(seed);
  const px = new Set();
  const w = Math.max(...art.map(r => r.length));
  const x0 = Math.floor((W - w) / 2);
  const y0 = WATERLINE - art.length + 2; // bottom row sits just under the waterline
  const hull = new Set();

  art.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') { px.add(`${x0 + x},${y0 + y}`); hull.add(`${x0 + x},${y0 + y}`); }
    }
  });

  // Water: a broken wave line, then a thinning ordered dither towards the frame edge.
  const phase = Math.floor(rnd() * 8);
  for (let y = WATERLINE + 1; y < H; y++) {
    const r = y - WATERLINE - 1;
    for (let x = 0; x < W; x++) {
      if (hull.has(`${x},${y}`)) continue;
      let on = false;
      if (r === 0) on = (x + phase) % 10 < 3;
      else if (r === 2) on = (x + phase + 5) % 10 < 2;
      else if (r === 4) on = (x + phase + 2) % 8 === 0;
      else if (r === 6) on = (x + phase + 6) % 12 === 0;
      if (on) px.add(`${x},${y}`);
    }
  }
  // Wake behind the stern and a bow wave, for moving vessels.
  const stern = x0 - 1;
  for (let i = 0; i < 6; i += 2) px.add(`${stern - i},${WATERLINE}`);

  // A couple of distant gulls.
  const birds = Math.floor(rnd() * 3);
  let firstLeft = true;
  for (let b = 0; b < birds; b++) {
    const left = b === 0 ? rnd() < 0.5 : !firstLeft;
    if (b === 0) firstLeft = left;
    const bx = left ? 2 + Math.floor(rnd() * 8) : W - 10 + Math.floor(rnd() * 6);
    const by = 1 + Math.floor(rnd() * 5);
    for (const [dx, dy] of [[0, 1], [1, 0], [2, 1], [3, 0], [4, 1]]) px.add(`${bx + dx},${by + dy}`);
  }

  return `<svg viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid meet" shape-rendering="crispEdges" aria-hidden="true"><path d="${runs(px)}"/></svg>`;
}

